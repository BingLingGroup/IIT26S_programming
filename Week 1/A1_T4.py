Num1 = 47
Num2 = 102
Sum = Num1 + Num2
Diff = Num2 - Num1
Product = Sum * Diff
print("{Num1} + {Num2} = {Sum}".format(Num1=Num1, Num2=Num2, Sum=Sum))
print("{Num2} - {Num1} = {Diff}".format(Num1=Num1, Num2=Num2, Diff=Diff))
print("{Sum} * {Diff} = {Product}".format(Sum=Sum, Diff=Diff, Product=Product))
print("({Num1} + {Num2}) * ({Num2} - {Num1}) = {Product}".format(Num1=Num1, Num2=Num2, Product=Product))
